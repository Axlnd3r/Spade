// Runs scripts/verify.mjs against the live contract and writes its result lines to src/verifyOutput.ts,
// so the terminal scene shows real output. Run it again after the final lock.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const r = spawnSync(process.execPath, ["scripts/verify.mjs"], { cwd: root, encoding: "utf8" });
if (r.status !== 0) {
  process.stderr.write(r.stdout + r.stderr);
  throw new Error(`verify.mjs exited ${r.status}`);
}
const lines = r.stdout.split("\n").filter((l) => /^(PASS|WARN|FAIL|SKIP) |^All checks|check\(s\) failed/.test(l));
const out = `// Generated by capture/verify-output.mjs on ${new Date().toISOString()}. Do not edit by hand.
export const VERIFY_LINES: string[] = ${JSON.stringify(lines, null, 2)};
`;
writeFileSync(new URL("src/verifyOutput.ts", new URL("../", import.meta.url)), out);
console.log(lines.join("\n"));
